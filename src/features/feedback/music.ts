/**
 * Background music: one quiet loop for the whole app. It plays only while the
 * setting is on, the app is in the foreground and nothing has put it on hold
 * (an ad playing its own audio). Failures are ignored.
 */
import { createAudioPlayer, type AudioPlayer } from 'expo-audio';
import { AppState } from 'react-native';

import { ensureAudioMode } from './audioMode';

const VOLUME = 0.3;

// Off until saved settings load, so a player who turned music off never hears it start.
let enabled = false;
let foreground = AppState.currentState === 'active';
const holds = new Set<symbol>();
let player: AudioPlayer | null = null;

function update() {
  const shouldPlay = enabled && foreground && holds.size === 0;
  try {
    if (shouldPlay) {
      if (!player) {
        ensureAudioMode();
        // Generated by `npm run audio` (scripts/generateAudio.ts); WAV so the loop is seamless.
        player = createAudioPlayer(require('../../../assets/audio/music.wav'));
        player.loop = true;
        player.volume = VOLUME;
      }
      player.play();
    } else {
      player?.pause();
    }
  } catch {
    // Audio unavailable on this platform.
  }
}

AppState.addEventListener('change', (state) => {
  foreground = state === 'active';
  update();
});

export function setMusicEnabled(value: boolean) {
  enabled = value;
  update();
}

/** Pauses the music until the returned function is called (e.g. while an ad plays). Safe to call release twice. */
export function holdMusic(): () => void {
  const hold = Symbol('hold');
  holds.add(hold);
  update();
  return () => {
    if (holds.delete(hold)) update();
  };
}
